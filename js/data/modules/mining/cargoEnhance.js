/* ===== 模块定义：货物强化（Cargo Enhancement）· 采矿类（紫）=====
 * ★ 一类模块一个文件；注册表在 `data/modules.js`（唯一入口，勿在别处再列一份）。
 *
 * 定位：**主动模块**（有目标、有自身冷却）——消耗**自身携带矿物**（`ore_cost`）＋**能量**（`energy_cost`），
 *       把**目标单位货舱中一件「尚未被强化」的货物**的加成系数**加性**提高 `bonus_add`（一次性、永久）。
 *
 * 目标：`{ kinds:['ally','self'], countMode:'single', maxCount:1 }` —— **单体、可为自己或队友**。
 *   · ★ **自身没有隐含优先级**：`self` 与 `ally` 同源同序，**按己方单位数组的自然顺序**取候选
 *     （“队列中轮到自身才为自身”）；**本模块不带 `prefer_self`**，故默认目标＝己方队列里第一个可强化者，
 *     玩家可在详情页手动指定自己/队友（手动目标优先级高于自然顺序）。
 *   · 与「矿物维修」「货物维修」的目标写法完全一致（同一套选择器与优先级链，引擎不硬编码 id）。
 *
 * 强化对象：**目标单位货舱中「已入舱」的货物**（唯一数据源 `cargoListOf(target)`，与「货物传输」
 *   「货物维修」同一口径）——**在装（锁定中、尚未入舱）的货物不可被强化**（在装货物仍在星区列表、
 *   不在货舱清单内；引擎另以 `_loadBy` 锁定索引作防御性复核）。
 *
 * 提升量：**新词条 `bonus_add`**（加性、逐级递增）——货物实例的 `bonus` 累加该值（**倍率语义**，
 *   `1 → 1.1` ⇒ 芯片加成段显示 `10%`，展示换算走唯一口径 `core/utils.js formatBonusPercent`，UI 不自算）。
 *   · ★ **词条原值、不乘任何类别系数**：`bonus_add` **不进**引擎量值词条表 `AMOUNT`，
 *     通用路径的 `词条值 × 类别系数` 缩放根本不适用于它（与「货物维修」的 `hp_per_ton` 同体例）。
 *   · 本词条**只在本模块（`type` 标签 `cargo_enhance`）的专属分支里被读取** ⇒ **对既有模块零影响**。
 *
 * ★ **一次性（永久）**：每件货物**只能被强化一次**——落地时置**一次性标记 `enhanced: true`**
 *   （写在**货物实体**上，**随实体走**：之后被传输、阵亡返还星区、再次装载都不清除），
 *   且以“该实体是否已标记”为**幂等判据**（重复落地绝不二次累加）。
 *
 * ★ **三条门控（Pass1，零数值变化）**：
 *     ① **目标货舱中没有「尚未被强化」的货物** → 不激活、不扣矿、不耗能、不进冷却
 *        （判定落在 Pass1 唯一门控出口 `canImpact`，与本模块的 `cargo_enhance` 分支同一处）；
 *     ② **矿物不足**（`ore_cost`）→ 既有成本门控拦住（**单位内预算** `ctx.oreAvail`，同单位多模块不超发）；
 *     ③ **能量不足**（`energy_cost`）→ 同上（`ctx.avail`）。
 *   三条都不满足即**静默不激活**（不扣矿物、不耗能量、不进冷却）——与采矿类既有模块完全同体例。
 *
 * ★ **选择口径（★ 未与用户确认，按最简可预期实现）**：**目标货舱列表顺序中第一件「尚未被强化」的货物**
 *   （FIFO＝先入舱者先被强化）。若该目标货舱内**没有任何未被强化的货物 ⇒ 不激活**（不扣矿不耗能）。
 *   ⚠ 如用户希望与「货物维修」的**吨位最小优先**统一，引擎只需把调用处 `pickCargoOf(...)` 的
 *     `mode` 由 `'fifo'` 改为 `'min'`（一处、一行）——**本件待用户裁决，未擅自改动**。
 *
 * ★ 记账与落地（铁律：Pass1 零数值变化、结算阶段统一落地）：
 *   · Pass1 **只记意图并冻结**（`__pending.cargoEnhances`：目标单位、目标货物实体、`bonus_add` 实际值）；
 *     成功激活时把该货物登记进**本 tick 的全局货物预留集合**（`cargoClaimedTick`，体例同星区侧
 *     `sectorClaimedTick`、货物链三处共用）⇒ 同 tick **任何单位/模块都不得再动这一件**（防争用、可复现）；
 *   · **结算步骤 3d-5（本模块新增的一小步，位于 3d 段末尾）** 统一写入：
 *     `货物.bonus += bonus_add` 且置 `货物.enhanced = true`（**唯一写入者**）。
 *     全序：`3d-1 矿物成本 → 3d-2 矿物输送 → 3d-3 货物传输 → 3d-4 货物维修消耗 → **3d-5 货物强化**
 *     → 步骤 4（4a/4b/4c/4d/4e）→ Phase B/B2 → 步骤 5 装载完成 → Phase C`。
 *     ⇒ **成本（能量步骤 3 / 矿物 3d-1）恒在写入之前**（“先成本、后效果”，与既有体例一致）；
 *       3d-5 在步骤 4（含全部判死）与步骤 5 之前 ⇒ 只对**本 tick 起始即已入舱**的货物生效，
 *       且与被传输/被消耗的货物**互不相交**（三处货物链共用同一预留集合，先到先得）⇒ 先后顺序不影响结果。
 *   · 写入落在**目标单位**身上（可为他人）⇒ 与“谁先谁后死”无关（判死都在其后）。
 *
 * ★ **低频战报** `battle.log.cargoEnhance`（★ 已实现）：**仅在真正写入时**记 1 条、**每模块每 tick ≤ 1 条**，
 *   成句在 **3d-5 落地处**（与数值同批）；`cargo`＝被强化货物显示名（与 UI 芯片同一名称口径）、
 *   `v`＝`bonus_add` 的**增量百分比**（唯一换算 `formatBonusPercent`）。
 */
export default {
  id: 'cargoEnhance',
  nameKey: 'module.cargoEnhance',
  name: '货物强化',
  category: 'mining',
  target: { kinds: ['ally', 'self'], countMode: 'single', maxCount: 1 },
  // ★ 能力标签 `cargo_enhance`：引擎**按标签识别**（不硬编码模块 id）；`bonus_add` 为本模块专属加性词条。
  effects: {
    type: ['cargo_enhance'],
    cooldown_ticks: 60,
    energy_cost: 60, // Lv1 占位
    ore_cost: 20,    // Lv1 占位：消耗自身携带矿物
    bonus_add: 0.1,  // Lv1 占位：货物加成系数 +0.1（倍率语义 ⇒ 芯片显示 +10%）
  },
  maxLevel: 16,
  // 逐级绝对值：只写差异、未填字段回退上一级（唯一解析 `entities/module.js resolveModuleCfg`）
  levels: [
    { level: 5, effects: { bonus_add: 0.15 } }, // 占位：+15%
    { level: 10, effects: { bonus_add: 0.2 } }, // 占位：+20%
    { level: 16, effects: { bonus_add: 0.3 } }, // 占位：+30%
  ],
};
